-- Remove the existing policy names and the names used by the earlier script
-- before recreating the intended public-read/owner-write policies.
do $$
declare
  table_name text;
  public_policy_name text;
  owner_policy_name text;
begin
  foreach table_name in array array[
    'portfolio',
    'projects',
    'skills',
    'certificates',
    'education',
    'research',
    'internships',
    'books'
  ] loop
    public_policy_name := 'Public can view ' || table_name;
    owner_policy_name := 'Owner manages ' || table_name;

    execute format(
      'drop policy if exists %I on public.%I',
      public_policy_name,
      table_name
    );
    execute format(
      'drop policy if exists %I on public.%I',
      owner_policy_name,
      table_name
    );
    execute format(
      'drop policy if exists %I on public.%I',
      'Public ' || table_name || ' read',
      table_name
    );
    execute format(
      'drop policy if exists %I on public.%I',
      'Owner ' || table_name || ' write',
      table_name
    );

    execute format(
      'create policy %I on public.%I for select to anon, authenticated using (true)',
      public_policy_name,
      table_name
    );
    execute format(
      'create policy %I on public.%I for all to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id)',
      owner_policy_name,
      table_name
    );
  end loop;
end $$;
